import type { Paddle } from "@paddle/paddle-node-sdk";
import type { BillingInterval } from "../billing.ts";

/**
 * Reads the billing interval of an existing Paddle subscription.
 * TRUXERA does not persist interval locally; the Paddle subscription's
 * billing_cycle is the authoritative source. Returns null when the
 * interval cannot be determined — callers must treat null as "unknown"
 * and degrade gracefully, never guess.
 */
export async function getPaddleSubscriptionInterval(
  paddle: Paddle,
  subscriptionId: string,
): Promise<BillingInterval | null> {
  try {
    const subscription = await paddle.subscriptions.get(subscriptionId);
    const interval = subscription.billingCycle?.interval;
    if (interval === "month") return "MONTHLY";
    if (interval === "year") return "ANNUAL";
    return null;
  } catch {
    return null;
  }
}

export type PaddleSubscriptionManagementUrls = {
  /** Paddle-hosted page to update the saved payment method. */
  updatePaymentMethod: string | null;
  /** Paddle-hosted page that cancels the subscription. */
  cancel: string | null;
  /** Paddle-hosted subscription details page. */
  viewSubscription: string | null;
};

/**
 * Fetches Paddle's hosted management URLs for a subscription. These are
 * generated by Paddle per-subscription and are the supported mechanism
 * for customers to update payment methods or cancel — TRUXERA never
 * handles card data. Returns null on any API failure so the UI can hide
 * the management actions rather than render broken links.
 */
export async function getPaddleSubscriptionManagement(
  paddle: Paddle,
  subscriptionId: string,
): Promise<PaddleSubscriptionManagementUrls | null> {
  try {
    const subscription = await paddle.subscriptions.get(subscriptionId);
    const urls = subscription.managementUrls;
    if (!urls) return null;
    return {
      updatePaymentMethod: urls.updatePaymentMethod ?? null,
      cancel: urls.cancel ?? null,
      viewSubscription: urls.viewSubscription ?? null,
    };
  } catch {
    return null;
  }
}
